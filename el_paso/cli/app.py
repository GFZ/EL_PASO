"""The ``el-paso`` command line entry point.

Groups every recipe under :mod:`el_paso.recipes` into one command tree, one
sub-command group per mission::

    el-paso list
    el-paso poes meped --start-time 2013-03-16 --satellite noaa15
    el-paso rbsp mageis-electrons --mag-field TS04 --bin-cadence 5min

Each command is generated by :func:`el_paso.cli.recipe_cli.build_recipe_command` from
the recipe's own signature, using the ``CLI_DEFAULTS`` declared in the recipe
module. That is the same builder the recipes' own ``python -m`` entry points use,
so both ways of invoking a recipe expose exactly the same options.
"""

